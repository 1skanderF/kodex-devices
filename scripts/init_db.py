def main() -> None:
    force = "--force" in sys.argv
    if os.path.exists(DB_PATH):
        if not force:
            print(f"{DB_PATH} уже существует; добавьте --force, чтобы пересоздать")
            sys.exit(1)
        os.remove(DB_PATH)

    conn = db.connect()
    db.init_schema(conn)
    conn.executemany(
        "INSERT INTO devices (id, serial, site, model, installed_at, last_seen) VALUES (?, ?, ?, ?, ?, ?)",
        DEVICES,
    )
    conn.executemany(
        "INSERT INTO tickets (device_id, status, title, description, created_at, resolved_at) "
        "VALUES (?, ?, ?, ?, ?, ?)",
        TICKETS,
    )
    conn.commit()
    conn.close()
